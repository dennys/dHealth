import 'package:dhealth/database/database.dart';
import 'package:dhealth/services/data_service.dart';
import 'package:dhealth/services/permission_service.dart';
import 'package:health/health.dart';
import 'package:mockito/annotations.dart';
import 'package:mockito/mockito.dart';
import 'package:test/test.dart';

import '../test/data_service_test.mocks.dart'; // Generated by Mockito

@GenerateMocks([Health, StepDatabase])
void main() {
  late MockHealth mockHealth;
  late _StepDatabaseMock mockDatabase;
  late StepDataService stepDataService;

  setUp(() {
    mockHealth = MockHealth();
    mockDatabase = _StepDatabaseMock();
    stepDataService = StepDataService(mockHealth, mockDatabase);
  });

  void allowRead() => when(mockHealth.hasPermissions(stepTypes, permissions: stepPermissions)).thenAnswer((_) async => true);

  void denyRead() => when(mockHealth.hasPermissions(stepTypes, permissions: stepPermissions)).thenAnswer((_) async => false);

  /// 模擬 Health Connect 的聚合 API：[stepsByDay] 的 key 是 yyyy-MM-dd，沒列的日子回 0。
  void stubFetch(Map<String, int> stepsByDay) {
    when(mockHealth.getTotalStepsInInterval(any, any)).thenAnswer((invocation) async {
      final from = invocation.positionalArguments[0] as DateTime;
      return stepsByDay[formatDateKey(from)] ?? 0;
    });
  }

  group('syncRange', () {
    test('同一天的步數直接採用 Health Connect 聚合值寫入（不再逐點加總，避免多來源重複計算）', () async {
      allowRead();
      stubFetch({'2025-03-10': 150});
      when(mockDatabase.getDailyStep(any)).thenAnswer((_) async => null);

      final result = await stepDataService.syncRange(DateTime(2025, 3, 10), DateTime(2025, 3, 10));

      expect(result.status, StepSyncStatus.success);
      expect(result.todaySkipped, isFalse);
      verify(mockDatabase.deleteDataInRange(any, any)).called(1);
      verify(mockDatabase.upsertDailyStep('2025-03-10', 150, any, isComplete: anyNamed('isComplete'))).called(1);
    });

    test('過去的日子 isComplete = true，今天 false', () async {
      allowRead();
      final now = DateTime.now();
      stubFetch({formatDateKey(now): 10});
      when(mockDatabase.getDailyStep(any)).thenAnswer((_) async => null);

      await stepDataService.syncRange(now, now);

      verify(mockDatabase.upsertDailyStep(formatDateKey(now), 10, any, isComplete: false)).called(1);
    });

    test('讀取失敗時绝不能刪除任何資料（舊版會先刪再讀，Health Connect 一失靈那個區間就永久消失）', () async {
      allowRead();
      when(mockHealth.getTotalStepsInInterval(any, any)).thenThrow(Exception('Health Connect 掛了'));

      final result = await stepDataService.syncRange(DateTime(2025, 3, 1), DateTime(2025, 3, 31));

      expect(result.status, StepSyncStatus.unavailable);
      verifyNever(mockDatabase.deleteDataInRange(any, any));
      verifyNever(mockDatabase.deleteAllData());
      verifyNever(mockDatabase.upsertDailyStep(any, any, any, isComplete: anyNamed('isComplete')));
    });

    test('聚合 API 回 null（讀不到）時同樣不能刪除任何資料', () async {
      allowRead();
      when(mockHealth.getTotalStepsInInterval(any, any)).thenAnswer((_) async => null);

      final result = await stepDataService.syncRange(DateTime(2025, 3, 1), DateTime(2025, 3, 2));

      expect(result.status, StepSyncStatus.unavailable);
      verifyNever(mockDatabase.deleteDataInRange(any, any));
      verifyNever(mockDatabase.upsertDailyStep(any, any, any, isComplete: anyNamed('isComplete')));
    });

    test('沒有讀取授權時同样不能刪除，且回報 permissionDenied', () async {
      denyRead();

      final result = await stepDataService.syncRange(DateTime(2025, 3, 1), DateTime(2025, 3, 31));

      expect(result.status, StepSyncStatus.permissionDenied);
      verifyNever(mockDatabase.deleteDataInRange(any, any));
      verifyNever(mockDatabase.upsertDailyStep(any, any, any, isComplete: anyNamed('isComplete')));
    });

    test('今天讀不到只跳過今天：其他天照常寫入，今天原有的列被保留', () async {
      allowRead();
      final now = DateTime.now();
      final yesterday = now.subtract(const Duration(days: 1));
      final todayKey = formatDateKey(now);
      when(mockHealth.getTotalStepsInInterval(any, any)).thenAnswer((invocation) async {
        final from = invocation.positionalArguments[0] as DateTime;
        return formatDateKey(from) == todayKey ? null : 500;
      });
      final existingToday = DailyStep(date: todayKey, stepCount: 321, lastUpdated: now, isComplete: false);
      when(mockDatabase.getDailyStep(any)).thenAnswer((invocation) async {
        final date = invocation.positionalArguments[0] as DateTime;
        return formatDateKey(date) == todayKey ? existingToday : null;
      });

      final result = await stepDataService.syncRange(yesterday, now);

      expect(result.status, StepSyncStatus.success);
      // 背景通知端靠這個旗號決定「今天無列」要不要走例外路
      expect(result.todaySkipped, isTrue);
      verify(mockDatabase.upsertDailyStep(formatDateKey(yesterday), 500, any, isComplete: true)).called(1);
      verify(mockDatabase.upsertDailyStep(todayKey, 321, any, isComplete: false)).called(1);
    });

    test('過去的日子讀不到仍然整個失敗（只有今天享有跳過的例外）', () async {
      allowRead();
      final now = DateTime.now();
      final yesterday = now.subtract(const Duration(days: 1));
      final yesterdayKey = formatDateKey(yesterday);
      when(mockHealth.getTotalStepsInInterval(any, any)).thenAnswer((invocation) async {
        final from = invocation.positionalArguments[0] as DateTime;
        return formatDateKey(from) == yesterdayKey ? null : 500;
      });

      final result = await stepDataService.syncRange(yesterday, now);

      expect(result.status, StepSyncStatus.unavailable);
      verifyNever(mockDatabase.deleteDataInRange(any, any));
    });

    test('真的讀到 0 步是正當結果：該區間被清空而不是保留舊值', () async {
      allowRead();
      stubFetch({});

      final result = await stepDataService.syncRange(DateTime(2025, 3, 10), DateTime(2025, 3, 11));

      expect(result.status, StepSyncStatus.success);
      verify(mockDatabase.deleteDataInRange(any, any)).called(1);
      verifyNever(mockDatabase.upsertDailyStep(any, any, any, isComplete: anyNamed('isComplete')));
    });

    test('刪除範圍不得超過使用者要的結束日（舊版 end +1 天且閉區間，多刪隔天）', () async {
      allowRead();
      stubFetch({});

      await stepDataService.syncRange(DateTime(2025, 3, 10), DateTime(2025, 3, 10));

      // verify(...).captured 是「所有被captured 的引數」平攤成一個清單
      final captured = verify(mockDatabase.deleteDataInRange(captureAny, captureAny)).captured;
      final DateTime start = captured[0] as DateTime;
      final DateTime end = captured[1] as DateTime;
      expect(formatDateKey(start), '2025-03-10');
      expect(formatDateKey(end), '2025-03-10');
      expect(end.day, 10, reason: '不能刪到隔天');
    });

    test('clearAllFirst 走 deleteAllData', () async {
      allowRead();
      stubFetch({});

      await stepDataService.syncRange(DateTime(2025, 3, 10), DateTime(2025, 3, 10), clearAllFirst: true);

      verify(mockDatabase.deleteAllData()).called(1);
      verifyNever(mockDatabase.deleteDataInRange(any, any));
    });

    test('end 早於 start 直接回報失敗，不碰 Health Connect 也不碰 DB', () async {
      final result = await stepDataService.syncRange(DateTime(2025, 3, 10), DateTime(2025, 3, 9));

      // 這是「使用者選的區間本身不合法」，要跟「Health Connect 讀不到」分開：
      // 後者要叫使用者去裝/開權限，前者只是重選日期。
      expect(result.status, StepSyncStatus.invalidRange);
      verifyNever(mockHealth.getHealthDataFromTypes(types: anyNamed('types'), startTime: anyNamed('startTime'), endTime: anyNamed('endTime')));
      verifyNever(mockDatabase.deleteDataInRange(any, any));
    });
  });

  group('syncNewData', () {
    test('資料庫有資料時從最後一天的前一天開始補', () async {
      final lastDate = DateTime(2025, 1, 1);
      when(mockDatabase.getLastDate()).thenAnswer((_) async => lastDate);
      allowRead();
      stubFetch({});

      await stepDataService.syncNewData();

      final captured = verify(mockDatabase.deleteDataInRange(captureAny, captureAny)).captured;
      expect(formatDateKey(captured[0] as DateTime), '2024-12-31');
    });

    test('資料庫全空時往回取 30 天（舊版被 getLastDate 的 now-7d 假值蓋住，只補到 8 天）', () async {
      when(mockDatabase.getLastDate()).thenAnswer((_) async => null);
      allowRead();
      stubFetch({});

      await stepDataService.syncNewData();

      final captured = verify(mockDatabase.deleteDataInRange(captureAny, captureAny)).captured;
      final start = captured[0] as DateTime;
      final days = DateTime.now().difference(start).inDays;
      expect(days, inInclusiveRange(29, 31));
    });
  });

  group('importFromPhone', () {
    test('分段跑完整個區間並回報進度', () async {
      allowRead();
      stubFetch({});
      when(mockDatabase.getLastDate()).thenAnswer((_) async => null);

      final progress = <double>[];
      final result = await stepDataService.importFromPhone(
        startDate: DateTime(2025, 1, 1),
        endDate: DateTime(2025, 3, 1),
        onProgress: progress.add,
      );

      expect(result.status, StepSyncStatus.success);
      expect(progress.last, 1.0);
      // 分段只是「分段讀」；寫入是全部讀成功後的一次性覆蓋（見下面那條回歸測試）
      verify(mockDatabase.deleteDataInRange(any, any)).called(1);
    });

    // 匯入是本案最危險的一條路：勾了「匯入前清除」時，舊實作第一段就把整張表清空，
    // 第 2 段讀取失敗（Health Connect 常見）就只留下第一段的資料，而且還是「匯入失敗」的訊息。
    test('其中一段讀不到時資料庫完全沒被動過（含 clearAllFirst）', () async {
      allowRead();
      var calls = 0;
      when(mockHealth.getTotalStepsInInterval(any, any)).thenAnswer((_) async {
        calls++;
        if (calls > 30) throw Exception('Health Connect 半路失靈'); // 第 31 天起是第二段
        return 1234;
      });

      final result = await stepDataService.importFromPhone(
        startDate: DateTime(2025, 1, 1),
        endDate: DateTime(2025, 3, 10),
        clearAllFirst: true,
      );

      expect(result.status, StepSyncStatus.unavailable);
      expect(calls, greaterThan(30), reason: '確實跑到第二段才失敗');
      verifyNever(mockDatabase.deleteAllData());
      verifyNever(mockDatabase.deleteDataInRange(any, any));
      verifyNever(mockDatabase.upsertDailyStep(any, any, any, isComplete: anyNamed('isComplete')));
    });

    test('其中一段失敗就立刻停止並回報', () async {
      denyRead();

      final result = await stepDataService.importFromPhone(startDate: DateTime(2025, 1, 1), endDate: DateTime(2025, 3, 1));

      expect(result.status, StepSyncStatus.permissionDenied);
      verifyNever(mockDatabase.deleteDataInRange(any, any));
    });
  });

  group('同步 serialize', () {
    // main.dart 的 _syncing 只擋得住 UI 自己，WorkManager 那條是另一條 isolate/另一條路。
    // 兩邊都是「先讀後寫 + transaction」，交錯時理論上會出現半套狀態 —— 這裡鎖住 serialize。
    test('兩個同步同時進來也不能交錯跑', () async {
      allowRead();
      var inside = 0, maxInside = 0;
      when(mockHealth.getTotalStepsInInterval(any, any)).thenAnswer((_) async {
        inside++;
        if (inside > maxInside) maxInside = inside;
        await Future<void>.delayed(const Duration(milliseconds: 5));
        inside--;
        return 10;
      });

      // 每次都只取「一天」→ 一次同步就一次 Health Connect 呼叫，量到的併發數才是
      // 「幾次同步之間有沒有交錯」，不會被單次同步內部的分批併發（一批 6 個）混淆。
      await Future.wait([
        stepDataService.syncRange(DateTime(2026, 3, 1), DateTime(2026, 3, 1)),
        stepDataService.syncRange(DateTime(2026, 3, 2), DateTime(2026, 3, 2)),
        stepDataService.importFromPhone(startDate: DateTime(2026, 3, 3), endDate: DateTime(2026, 3, 3)),
      ]);

      expect(maxInside, 1, reason: '讀取必須一條接一條，不能兩三次 Health Connect 同步交錯寫進同一個區間');
    });
  });

  group('fetchHourlyTotals', () {
    // 固定一個「現在」：今天 10:30 → 該查 0..10 共 11 小時
    final now = DateTime(2026, 3, 10, 10, 30);
    const hours = 11;

    void stubByHour(Map<int, int?> stepsByHour, {Map<int, int>? secondTry}) {
      final seen = <int, int>{};
      when(mockHealth.getTotalStepsInInterval(any, any)).thenAnswer((invocation) async {
        final from = invocation.positionalArguments[0] as DateTime;
        final hour = from.hour;
        seen[hour] = (seen[hour] ?? 0) + 1;
        if (secondTry != null && seen[hour] != null && seen[hour]! > 1) return secondTry[hour];
        return stepsByHour[hour];
      });
    }

    test('逐小時都讀到 → 0..現在 每格都有值', () async {
      allowRead();
      stubByHour({for (var h = 0; h < hours; h++) h: h * 10});

      final totals = await stepDataService.fetchHourlyTotals(now);

      expect(totals?.length, hours);
      expect(totals?[0], 0);
      expect(totals?[10], 100);
    });

    // 舊版：任何一個小時回 null 就整批 throw，23 個好小時一起陪葬，主畫面變成「讀不到」。
    test('某一小時讀不到：只缺那一格，其他小時要留著（不再牺牲整天）', () async {
      allowRead();
      stubByHour({for (var h = 0; h < hours; h++) h: 50, 5: null});

      final totals = await stepDataService.fetchHourlyTotals(now);

      expect(totals, isNotNull);
      expect(totals!.containsKey(5), isFalse, reason: '讀不到的那格要省略，不能當成 0 步寫進去');
      expect(totals.length, hours - 1);
      expect(totals[4], 50);
      expect(totals[6], 50);
    });

    test('單小時先讀不到、補插那次讀到 → 用補插到的值', () async {
      allowRead();
      stubByHour({for (var h = 0; h < hours; h++) h: 50, 5: null}, secondTry: {for (var h = 0; h < hours; h++) h: 50, 5: 77});

      final totals = await stepDataService.fetchHourlyTotals(now);

      expect(totals?[5], 77);
      expect(totals?.length, hours);
    });

    test('單小時丟例外不影響整天（例外當成「這一格讀不到」處理）', () async {
      allowRead();
      when(mockHealth.getTotalStepsInInterval(any, any)).thenAnswer((invocation) async {
        final from = invocation.positionalArguments[0] as DateTime;
        if (from.hour == 3) throw Exception('Health Connect 抖了一下');
        return 20;
      });

      final totals = await stepDataService.fetchHourlyTotals(now);

      expect(totals, isNotNull);
      expect(totals!.containsKey(3), isFalse);
      expect(totals.length, hours - 1);
    });

    test('全部小時都讀不到 → 回 null（圖表畫「讀不到」而不是 0 步）', () async {
      allowRead();
      stubByHour({for (var h = 0; h < hours; h++) h: null});

      expect(await stepDataService.fetchHourlyTotals(now), isNull);
    });

    test('沒有讀取授權 → null，且一次都不去查 Health Connect', () async {
      denyRead();

      expect(await stepDataService.fetchHourlyTotals(now), isNull);
      verifyNever(mockHealth.getTotalStepsInInterval(any, any));
    });
  });
}

/// syncRange 把刪除與寫入包在 transaction 裡；Mockito 對泛型 transaction 只能回
/// 一個假的 Future（closure 根本不會被執行），那樣就驗不到裡面的 delete/upsert。
/// 直接覆寫成「真的把 closure 跑掉」，其餘方法仍是可 when()/verify() 的 mock。
class _StepDatabaseMock extends MockStepDatabase {
  @override
  Future<T> transaction<T>(Future<T> Function()? action, {bool? requireNew}) => action!();
}
