// Generate mocks for Health and StepDatabase
@GenerateMocks([Health, StepDatabase])
void main() {
  late MockHealth mockHealth;
  late MockStepDatabase mockDatabase;
  late StepDataService stepDataService;

  String formatDate(DateTime date) {
    return "${date.year}-${date.month.toString().padLeft(2, '0')}-${date.day.toString().padLeft(2, '0')}";
  }

  setUp(() {
    mockHealth = MockHealth();
    mockDatabase = MockStepDatabase();
    stepDataService = StepDataService(health: mockHealth, database: mockDatabase);
  });

  group('StepDataService Tests', () {
    // Test fetchData
    group('fetchData', () {
      test('returns health data when permissions are granted', () async {
        final startTime = DateTime(2025, 1, 1);
        final endTime = DateTime(2025, 1, 2);
        final healthData = [
          HealthDataPoint(
            uuid: 'uuid1',
            value: NumericHealthValue(numericValue: 100),
            type: HealthDataType.STEPS,
            unit: HealthDataUnit.COUNT,
            dateFrom: startTime,
            dateTo: endTime,
            sourcePlatform: HealthPlatformType.googleHealthConnect,
            sourceDeviceId: 'deviceId',
            sourceId: 'sourceId',
            sourceName: 'HealthApp',
            recordingMethod: RecordingMethod.automatic,
            workoutSummary: null,
          ),
        ];

        when(mockHealth.hasPermissions([HealthDataType.STEPS], permissions: [HealthDataAccess.READ])).thenAnswer((_) async => true);
        when(
          mockHealth.getHealthDataFromTypes(types: [HealthDataType.STEPS], startTime: startTime, endTime: endTime),
        ).thenAnswer((_) async => healthData);
        when(mockHealth.removeDuplicates(healthData)).thenReturn(healthData);

        final result = await stepDataService.fetchData(startTime: startTime, endTime: endTime);

        expect(result, isNotNull);
        expect(result!.length, 1);
        // expect(result.first.value.numericValue.toInt(), 100);
        expect(result.first.value, NumericHealthValue(numericValue: 100));
        verify(mockHealth.hasPermissions([HealthDataType.STEPS], permissions: [HealthDataAccess.READ])).called(1);
        verify(mockHealth.getHealthDataFromTypes(types: [HealthDataType.STEPS], startTime: startTime, endTime: endTime)).called(1);
      });

      test('returns null when permissions are not granted', () async {
        final startTime = DateTime(2025, 1, 1);
        final endTime = DateTime(2025, 1, 2);

        when(mockHealth.hasPermissions([HealthDataType.STEPS], permissions: [HealthDataAccess.READ])).thenAnswer((_) async => false);

        final result = await stepDataService.fetchData(startTime: startTime, endTime: endTime);

        expect(result, isNull);
        verify(mockHealth.hasPermissions([HealthDataType.STEPS], permissions: [HealthDataAccess.READ])).called(1);
        verifyNever(mockHealth.getHealthDataFromTypes(types: anyNamed('types'), startTime: anyNamed('startTime'), endTime: anyNamed('endTime')));
      });

      test('handles exceptions gracefully', () async {
        final startTime = DateTime(2025, 1, 1);
        final endTime = DateTime(2025, 1, 2);

        when(mockHealth.hasPermissions([HealthDataType.STEPS], permissions: [HealthDataAccess.READ])).thenThrow(Exception('Permission check failed'));

        final result = await stepDataService.fetchData(startTime: startTime, endTime: endTime);

        expect(result, isNull);
      });
    });

    // Test processAndSaveStepData
    group('processAndSaveStepData', () {
      test('processes and saves step data correctly', () async {
        final date = DateTime(2025, 1, 1);
        final healthData = [
          HealthDataPoint(
            uuid: 'uuid1',
            value: NumericHealthValue(numericValue: 100),
            type: HealthDataType.STEPS,
            unit: HealthDataUnit.COUNT,
