            dateTo: date.add(Duration(hours: 1)),
            sourcePlatform: HealthPlatformType.googleHealthConnect,
            sourceDeviceId: 'deviceId',
            sourceId: 'sourceId',
            sourceName: 'HealthApp',
            recordingMethod: RecordingMethod.automatic,
            workoutSummary: null,
          ),
          HealthDataPoint(
            uuid: 'uuid2',
            value: NumericHealthValue(numericValue: 50),
            type: HealthDataType.STEPS,
            unit: HealthDataUnit.COUNT,
            dateFrom: date,
            dateTo: date.add(Duration(hours: 2)),
            sourcePlatform: HealthPlatformType.googleHealthConnect,
            sourceDeviceId: 'deviceId',
            sourceId: 'sourceId',
            sourceName: 'HealthApp',
            recordingMethod: RecordingMethod.automatic,
            workoutSummary: null,
          ),
        ];

        when(mockDatabase.getDailyStep(date)).thenAnswer((_) async => null);
        when(mockDatabase.upsertDailyStep(any, any, any, isComplete: anyNamed('isComplete'))).thenAnswer((_) async => null);

        await stepDataService.processAndSaveStepData(healthData);

        verify(mockDatabase.getDailyStep(date)).called(1);
        verify(
          mockDatabase.upsertDailyStep(
            formatDate(date),
            150, // 100 + 50
            any,
            isComplete: true, // Day is before "now" (March 31, 2025)
          ),
        ).called(1);
      });

      test('updates existing incomplete data', () async {
        final date = DateTime(2025, 1, 1);
        final existingStep = DailyStep(date: formatDate(date), stepCount: 50, lastUpdated: DateTime.now(), isComplete: false);
        final healthData = [
          HealthDataPoint(
            uuid: 'uuid1',
            value: NumericHealthValue(numericValue: 100),
            type: HealthDataType.STEPS,
            unit: HealthDataUnit.COUNT,
            dateFrom: date,
            dateTo: date.add(Duration(hours: 1)),
            sourcePlatform: HealthPlatformType.googleHealthConnect,
            sourceDeviceId: 'deviceId',
            sourceId: 'sourceId',
            sourceName: 'HealthApp',
            recordingMethod: RecordingMethod.automatic,
            workoutSummary: null,
          ),
        ];

        when(mockDatabase.getDailyStep(date)).thenAnswer((_) async => existingStep);
        when(mockDatabase.upsertDailyStep(any, any, any, isComplete: anyNamed('isComplete'))).thenAnswer((_) async => null);

        await stepDataService.processAndSaveStepData(healthData);

        verify(
          mockDatabase.upsertDailyStep(
            formatDate(date),
            150, // 50 (existing) + 100 (new)
            any,
            isComplete: true,
          ),
        ).called(1);
      });
    });

