import 'package:dhealth/services/permission_service.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:health/health.dart';
import 'package:mockito/annotations.dart';
import 'package:mockito/mockito.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:shared_preferences_platform_interface/in_memory_shared_preferences_async.dart';
import 'package:shared_preferences_platform_interface/shared_preferences_async_platform_interface.dart';

import 'permission_service_test.mocks.dart'; // Generated by Mockito

/// requestStepAccess 是權限的唯一入口：以前它恆回 true（每個 return false 都被
/// 註解掉），於是在使用者面前讀到 0 步看起來像「今天真的沒走路」而不是「沒權限」。
/// 這裡鎖住「關鍵權限拿不到一定要回 PermissionFailure」的語意。
///
/// 注意：activityRecognition 那支只在 Android 走（Platform.isAndroid），host 測試
/// 測不到；wantNotifications 一律傳 false 跳過 permission_handler 的靜態呼叫
/// （那是平台 channel，host 上沒有 plugin）。
@GenerateMocks([Health])
void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  late MockHealth health;
  late SharedPreferencesAsync prefs;
  late PermissionService service;

  setUp(() {
    SharedPreferencesAsyncPlatform.instance = InMemorySharedPreferencesAsync.empty();
    prefs = SharedPreferencesAsync();
    health = MockHealth();
    service = PermissionService(health, prefs);
  });

  /// 加分項（歷史/背景讀取）預設已授權，不會走到 request 那支。
  void stubOptionalGranted() {
    when(health.isHealthDataHistoryAuthorized()).thenAnswer((_) async => true);
    when(health.isHealthDataInBackgroundAuthorized()).thenAnswer((_) async => true);
  }

  test('已有讀取權限 → 直接放行（null）', () async {
    when(health.hasPermissions(stepTypes, permissions: stepPermissions)).thenAnswer((_) async => true);
    stubOptionalGranted();

    expect(await service.requestStepAccess(wantNotifications: false), isNull);
  });

  test('沒有權限但授權成功 → 放行', () async {
    when(health.hasPermissions(stepTypes, permissions: stepPermissions)).thenAnswer((_) async => false);
    when(health.requestAuthorization(stepTypes, permissions: stepPermissions)).thenAnswer((_) async => true);
    stubOptionalGranted();

    expect(await service.requestStepAccess(wantNotifications: false), isNull);
  });

  test('沒有權限且授權失敗 → healthRead（不能恆回 true）', () async {
    when(health.hasPermissions(stepTypes, permissions: stepPermissions)).thenAnswer((_) async => false);
    when(health.requestAuthorization(stepTypes, permissions: stepPermissions)).thenAnswer((_) async => false);

    expect(await service.requestStepAccess(wantNotifications: false), PermissionFailure.healthRead);
  });

  test('hasPermissions 回 null（平台不支援）→ 走授權，授權失敗 → healthRead', () async {
    when(health.hasPermissions(stepTypes, permissions: stepPermissions)).thenAnswer((_) async => null);
    when(health.requestAuthorization(stepTypes, permissions: stepPermissions)).thenAnswer((_) async => false);

    expect(await service.requestStepAccess(wantNotifications: false), PermissionFailure.healthRead);
  });

  test('health 呼叫炸掉 → healthRead（例外不能漏出去）', () async {
    when(health.hasPermissions(stepTypes, permissions: stepPermissions)).thenThrow(StateError('boom'));

    expect(await service.requestStepAccess(wantNotifications: false), PermissionFailure.healthRead);
  });
}