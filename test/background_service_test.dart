import 'package:dhealth/database/database.dart';
import 'package:dhealth/services/background_service.dart';
import 'package:dhealth/services/data_service.dart';
import 'package:dhealth/services/notification_service.dart';
import 'package:dhealth/settings_keys.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:mockito/annotations.dart';
import 'package:mockito/mockito.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:shared_preferences_platform_interface/in_memory_shared_preferences_async.dart';
import 'package:shared_preferences_platform_interface/shared_preferences_async_platform_interface.dart';

import 'background_service_test.mocks.dart'; // Generated by Mockito
import 'data_service_test.mocks.dart'; // MockStepDatabase

/// executeTask 是背景通知的總開關：以前它是 static + GetIt + 平台 channel，
/// 整條路在測試裡走不通，於是「今天讀不到就靜默」那種 bug 只能靠真機撞出來。
/// 現在依賴全部注入（StepDataService mock、NotificationService 的 permission/display
/// 縫、prefs 走記憶體），每一條分支都有測試。
@GenerateMocks([StepDataService])
void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  late MockStepDataService mockData;
  late MockStepDatabase mockDb;
  late NotificationService notifications;
  late BackgroundService service;
  late SharedPreferencesAsync prefs;
  final displayed = <(String, String)>[]; // (title, body)

  setUp(() async {
    SharedPreferencesAsyncPlatform.instance = InMemorySharedPreferencesAsync.empty();
    prefs = SharedPreferencesAsync();
    displayed.clear();
    notifications = NotificationService(
      prefs,
      permissionCheck: () async => true,
      display: (title, body) async {
        displayed.add((title, body));
        return true;
      },
    );
    mockData = MockStepDataService();
    mockDb = MockStepDatabase();
    when(mockData.database).thenReturn(mockDb);
    when(mockDb.getLastDate()).thenAnswer((_) async => null); // 沒有資料 → 不觸發備份提醒
    service = BackgroundService(mockData, notifications, prefs);
    // 全天視窗：測試結果不該取決於跑測試的時刻。
    await prefs.setInt(Prefs.activeStartHour, 0);
    await prefs.setInt(Prefs.activeEndHour, 23);
  });

  /// 預設：同步成功、今天有 [steps] 步。
  Future<void> stubSync({int steps = 0, bool todaySkipped = false, StepSyncStatus status = StepSyncStatus.success}) async {
    final now = DateTime.now();
    final row = steps > 0 ? DailyStep(date: formatDateKey(now), stepCount: steps, lastUpdated: now, isComplete: false) : null;
    when(mockDb.getDailyStep(any)).thenAnswer((_) async => row);
    when(mockData.syncNewData()).thenAnswer((_) async => (status: status, detail: null, todaySkipped: todaySkipped));
  }

  Future<bool> sent(String kind) async => (await prefs.getInt('notification_last_sent_$kind')) != null;

  group('同步失敗 → 例外通知', () {
    test('unavailable（Health Connect 讀不到）→ 發例外通知', () async {
      await stubSync(status: StepSyncStatus.unavailable);

      await service.executeTask();

      expect(displayed, hasLength(1));
      expect(await sent('notification_exception'), isTrue);
    });

    test('permissionDenied → 同樣發例外通知', () async {
      await stubSync(status: StepSyncStatus.permissionDenied);

      await service.executeTask();

      expect(await sent('notification_exception'), isTrue);
    });
  });

  group('同步成功但今天無列', () {
    // 回歸：2ad6e9c 之後「今天讀不到」不再讓整個同步失敗，executeTask 若只看
    // status 就會什麼都不發（達標/鼓勵/例外全靜默）。
    test('todaySkipped 且今天沒有舊列 → 發例外通知', () async {
      await stubSync(todaySkipped: true);

      await service.executeTask();

      expect(await sent('notification_exception'), isTrue);
    });

    test('todaySkipped 但今天有舊列（保留值）→ 不發例外，照舊走步數判斷', () async {
      await stubSync(steps: 321, todaySkipped: true); // 321 < 6000-1000 → none

      await service.executeTask();

      expect(displayed, isEmpty);
    });
  });

  group('步數判斷', () {
    test('達標（7000 ≥ 6000）→ 只發達標通知', () async {
      await stubSync(steps: 7000);

      await service.executeTask();

      expect(await sent('notification_reach_goal'), isTrue);
      expect(await sent('notification_motivation'), isFalse);
      expect(await sent('notification_exception'), isFalse);
    });

    test('就差一點點（5500，差 500 ≤ 1000）→ 只發鼓勵通知', () async {
      await stubSync(steps: 5500);

      await service.executeTask();

      expect(await sent('notification_motivation'), isTrue);
      expect(await sent('notification_reach_goal'), isFalse);
    });

    test('離目標還遠（1000）→ 什麼都不發', () async {
      await stubSync(steps: 1000);

      await service.executeTask();

      expect(displayed, isEmpty);
    });

    test('真的 0 步是正當結果 → 什麼都不發（不能當成例外）', () async {
      await stubSync(steps: 0);

      await service.executeTask();

      expect(displayed, isEmpty);
    });
  });

  group('開關與時段', () {
    test('通知總開關關掉 → 達標也不發', () async {
      await prefs.setBool(Prefs.notificationsEnabled, false);
      await stubSync(steps: 7000);

      await service.executeTask();

      expect(displayed, isEmpty);
    });

    test('不在通知時段內 → 達標也不發', () async {
      // 動態挑一個「現在不在」的小時（12 小時外），測試結果不取決於跑測試的時刻。
      final h = (DateTime.now().hour + 12) % 24;
      await prefs.setInt(Prefs.activeStartHour, h);
      await prefs.setInt(Prefs.activeEndHour, h);
      await stubSync(steps: 7000);

      await service.executeTask();

      expect(displayed, isEmpty);
    });

    test('節流：例外通知剛發過 → 同一間隔內不再發', () async {
      await notifications.markSent('notification_exception', now: DateTime.now());
      await stubSync(status: StepSyncStatus.unavailable);

      await service.executeTask();

      expect(displayed, isEmpty);
    });
  });

  group('備份提醒', () {
    test('有資料但從沒匯出過 → 發備份提醒（步數本身不發）', () async {
      when(mockDb.getLastDate()).thenAnswer((_) async => DateTime.now().subtract(const Duration(days: 3)));
      await stubSync(steps: 1000);

      await service.executeTask();

      expect(await sent('notification_backup_reminder'), isTrue);
      expect(await sent('notification_reach_goal'), isFalse);
    });

    test('剛匯出過 → 不發備份提醒', () async {
      when(mockDb.getLastDate()).thenAnswer((_) async => DateTime.now().subtract(const Duration(days: 3)));
      await prefs.setInt(Prefs.lastExportAt, DateTime.now().millisecondsSinceEpoch);
      await stubSync(steps: 1000);

      await service.executeTask();

      expect(await sent('notification_backup_reminder'), isFalse);
    });

    // 回歸：節流間隔曾誤用同步頻率（預設 15 分鐘）—— 備份過期後每次背景同步
    // 都再發一顆（一天 96 顆）。條件是天級的，節流也該是天級的。
    test('節流是天級：30 分鐘前發過就不該再發（15 分鐘同步頻率不能當節流）', () async {
      when(mockDb.getLastDate()).thenAnswer((_) async => DateTime.now().subtract(const Duration(days: 3)));
      await prefs.setInt(Prefs.lastExportAt, DateTime.now().subtract(const Duration(days: 15)).millisecondsSinceEpoch);
      const key = 'notification_last_sent_${Prefs.backupReminder}';
      await prefs.setInt(key, DateTime.now().subtract(const Duration(minutes: 30)).millisecondsSinceEpoch);
      await stubSync(steps: 1000);

      await service.executeTask();

      expect(await prefs.getInt(key), DateTime.now().subtract(const Duration(minutes: 30)).millisecondsSinceEpoch,
          reason: '24h 節流內不該再發（時間戳不該被更新）');
    });
  });

  group('inputData 回退', () {
    test('prefs 沒有 dailyStepGoal 時用 inputData 的（WorkManager 排程時帶的快照）', () async {
      await stubSync(steps: 150);

      await service.executeTask({'dailyStepGoal': 100});

      expect(await sent('notification_reach_goal'), isTrue);
    });
  });
}