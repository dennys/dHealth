// 1. First, let's define our drift database table

import 'package:drift/drift.dart';

// 2. Database class
part 'database.g.dart'; // This will be generated by drift

// This will be the table structure for our daily step data
class DailySteps extends Table {
  // Primary key - date stored as text in format YYYY-MM-DD
  TextColumn get date => text()();
  // Total step count for the day
  IntColumn get stepCount => integer()();
  // Last update timestamp to track when this record was last modified
  DateTimeColumn get lastUpdated => dateTime()();
  // Flag to indicate if this data is considered complete/final
  BoolColumn get isComplete => boolean().withDefault(const Constant(false))();

  @override
  Set<Column> get primaryKey => {date};
}

@DriftDatabase(tables: [DailySteps])
class StepDatabase extends _$StepDatabase {
  StepDatabase(super.e);

  @override
  int get schemaVersion => 1;

  // Get all daily step records
  Future<List<DailyStep>> getAllDailySteps() => select(dailySteps).get();

  // Get a specific day's step data
  Future<DailyStep?> getDailyStep(DateTime date) {
    return (select(dailySteps)..where((t) => t.date.equals(_formatDate(date)))).getSingleOrNull();
  }

  // Get the last updated date
  Future<DateTime?> getLastDate() async {
    final query =
        select(dailySteps)
          ..orderBy([(t) => OrderingTerm.desc(t.date)])
          ..limit(1);
    // final results = await query.get(); // Fetch all matching rows
    final result = await query.getSingleOrNull();
    return DateTime.parse(result!.date); // Convert string to DateTime
  }

  // Insert or update a daily step entry
  Future<void> upsertDailyStep(String date, int steps, DateTime lastUpdated, {bool isComplete = false}) async {
    await into(dailySteps).insertOnConflictUpdate(
      DailyStepsCompanion(date: Value(date), stepCount: Value(steps), lastUpdated: Value(lastUpdated), isComplete: Value(isComplete)),
    );
  }

  // Mark a specific day as complete
  Future<void> markDayAsComplete(String date) async {
    await (update(dailySteps)..where((t) => t.date.equals(date))).write(const DailyStepsCompanion(isComplete: Value(true)));
  }

  // Delete all data (for complete refresh)
  Future<void> deleteAllData() async {
    await delete(dailySteps).go();
  }

  // Delete data for a specific date range
  Future<void> deleteDataInRange(DateTime start, DateTime end) async {
    String startDate = _formatDate(start);
    String endDate = _formatDate(end);
    await (delete(dailySteps)..where((t) => t.date.isBiggerOrEqualValue(startDate) & t.date.isSmallerOrEqualValue(endDate))).go();
  }

  // Helper method to format date as YYYY-MM-DD
  static String _formatDate(DateTime date) {
    return "${date.year}-${date.month.toString().padLeft(2, '0')}-${date.day.toString().padLeft(2, '0')}";
  }

  // 1. Map structure for date to steps mapping
  Future<Map<DateTime, int>> getStepsMap(DateTime startDate, DateTime endDate) async {
    final formattedStart = _formatDate(startDate);
    final formattedEnd = _formatDate(endDate);
    final results =
        await (select(dailySteps)..where((t) => t.date.isBiggerOrEqualValue(formattedStart) & t.date.isSmallerOrEqualValue(formattedEnd))).get();

    return Map.fromEntries(results.map((entry) => MapEntry(DateTime.parse(entry.date), entry.stepCount)));
  }

  // 2. Get daily average steps for 14-day period
  // Future<Map<DateTime, int>> getDailyAverageSteps(DateTime startDate, DateTime endDate) async {
