// This will be the table structure for our daily step data
class DailySteps extends Table {
  // Primary key - date stored as text in format YYYY-MM-DD
  TextColumn get date => text()();
  // Total step count for the day
  IntColumn get stepCount => integer()();
  // Last update timestamp to track when this record was last modified
  DateTimeColumn get lastUpdated => dateTime()();
  // Flag to indicate if this data is considered complete/final
  BoolColumn get isComplete => boolean().withDefault(const Constant(false))();

  @override
  Set<Column> get primaryKey => {date};
}

@DriftDatabase(tables: [DailySteps])
class StepDatabase extends _$StepDatabase {
  StepDatabase(super.e);

  @override
  int get schemaVersion => 1;

  // Get all daily step records
  Future<List<DailyStep>> getAllDailySteps() => select(dailySteps).get();

  // Get a specific day's step data
  Future<DailyStep?> getDailyStep(DateTime date) {
    return (select(dailySteps)..where((t) => t.date.equals(_formatDate(date)))).getSingleOrNull();
  }

  // Get the last updated date
  Future<DateTime?> getLastUpdatedDate() async {
    final query = select(dailySteps)..orderBy([(t) => OrderingTerm.desc(t.lastUpdated)]);
    final result = await query.getSingleOrNull();
    return result?.lastUpdated;
  }

  // Insert or update a daily step entry
  Future<void> upsertDailyStep(String date, int steps, DateTime lastUpdated, {bool isComplete = false}) async {
    await into(dailySteps).insertOnConflictUpdate(
      DailyStepsCompanion(date: Value(date), stepCount: Value(steps), lastUpdated: Value(lastUpdated), isComplete: Value(isComplete)),
    );
  }

  // Mark a specific day as complete
  Future<void> markDayAsComplete(String date) async {
    await (update(dailySteps)..where((t) => t.date.equals(date))).write(const DailyStepsCompanion(isComplete: Value(true)));
  }

  // Delete all data (for complete refresh)
  Future<void> deleteAllData() async {
    await delete(dailySteps).go();
  }

  // Delete data for a specific date range
  Future<void> deleteDataInRange(DateTime start, DateTime end) async {
    String startDate = _formatDate(start);
    String endDate = _formatDate(end);
    await (delete(dailySteps)..where((t) => t.date.isBiggerOrEqualValue(startDate) & t.date.isSmallerOrEqualValue(endDate))).go();
  }

  // Helper method to format date as YYYY-MM-DD
  static String _formatDate(DateTime date) {
    return "${date.year}-${date.month.toString().padLeft(2, '0')}-${date.day.toString().padLeft(2, '0')}";
  }

  // 1. Map structure for date to steps mapping
  Future<Map<DateTime, int>> getStepsMap(DateTime startDate, DateTime endDate) async {
    final formattedStart = _formatDate(startDate);
    final formattedEnd = _formatDate(endDate);
    final results =
        await (select(dailySteps)..where((t) => t.date.isBiggerOrEqualValue(formattedStart) & t.date.isSmallerOrEqualValue(formattedEnd))).get();

    return Map.fromEntries(results.map((entry) => MapEntry(DateTime.parse(entry.date), entry.stepCount)));
  }

  // 2. Get daily average steps for 14-day period
  Future<Map<DateTime, int>> getDailyAverageSteps(DateTime startDate, DateTime endDate) async {
    final difference = endDate.difference(startDate).inDays;
    if (difference != 13) {
      // 14 days including start and end
      throw Exception('Period must be exactly 14 days');
    }

    final stepsMap = await getStepsMap(startDate, endDate);
    final totalSteps = stepsMap.values.fold(0, (sum, steps) => sum + steps);
    final dailyAverage = (totalSteps / 7).round(); // Average over 7 days

    return {startDate: dailyAverage};
  }

  // 3. Get all weekly steps
  Future<List<MapEntry<DateTime, int>>> getAllWeeklySteps(DateTime startDate, DateTime endDate) async {
    final stepsMap = await getStepsMap(startDate, endDate);
    final results = <MapEntry<DateTime, int>>[];

    DateTime currentStart = startDate;
    while (currentStart.isBefore(endDate)) {
      final weekEnd = currentStart.add(const Duration(days: 6));
      final weekSteps = stepsMap.entries
          .where((entry) => !entry.key.isBefore(currentStart) && !entry.key.isAfter(weekEnd))
          .fold(0, (sum, entry) => sum + entry.value);

      if (weekSteps > 0) {
        results.add(MapEntry(currentStart, weekSteps));
      }
      currentStart = weekEnd.add(const Duration(days: 1));
    }

    return results;
  }

  // 4. Get all monthly steps
  Future<List<MapEntry<DateTime, int>>> getAllMonthlySteps(DateTime startDate, DateTime endDate) async {
    if (endDate.isBefore(startDate)) {
      throw Exception('endDate must be after startDate');
    }

    final stepsMap = await getStepsMap(startDate, endDate);
    final results = <MapEntry<DateTime, int>>[];

    DateTime currentMonth = DateTime(startDate.year, startDate.month, 1);
    while (currentMonth.isBefore(endDate) || currentMonth.isAtSameMomentAs(endDate)) {
      final monthEnd = DateTime(currentMonth.year, currentMonth.month + 1, 0);
      final monthSteps = stepsMap.entries
          .where((entry) => !entry.key.isBefore(currentMonth) && !entry.key.isAfter(monthEnd))
          .fold(0, (sum, entry) => sum + entry.value);

      if (monthSteps > 0) {
        results.add(MapEntry(currentMonth, monthSteps));
      }
      currentMonth = DateTime(currentMonth.year, currentMonth.month + 1, 1);
    }

    return results;
  }

  // 5. Get all yearly steps
  Future<List<MapEntry<DateTime, int>>> getAllYearlySteps() async {
    final allSteps = await getAllDailySteps();
    if (allSteps.isEmpty) return [];

    final stepsMap = Map.fromEntries(allSteps.map((entry) => MapEntry(DateTime.parse(entry.date), entry.stepCount)));

    final firstDate = DateTime.parse(allSteps.first.date);
    final yearStart = DateTime(firstDate.year, 1, 1);

    final totalSteps = stepsMap.values.fold(0, (sum, steps) => sum + steps);
    return [MapEntry(yearStart, totalSteps)];
  }
}

// 3. Now, let's create a service class to handle health data fetching and processing
class StepDataService {
  final Health health;
  final StepDatabase database;

  StepDataService({required this.health, required this.database});

  // Fetch health data for the specified time range
  Future<List<HealthDataPoint>?> fetchData({required DateTime startTime, required DateTime endTime}) async {
    try {
      final types = [HealthDataType.STEPS];
      final permissions = [HealthDataAccess.READ];

      // Ensure we have permissions
      bool? hasPermissions = await health.hasPermissions(types, permissions: permissions);

      if (hasPermissions == false) {
        debugPrint("Not authorized to fetch data");
        return null;
      }

      // Get health data
      List<HealthDataPoint> healthData = await health.getHealthDataFromTypes(types: types, startTime: startTime, endTime: endTime);

      // Remove duplicates
      return health.removeDuplicates(healthData);
    } catch (error) {
      debugPrint("Exception in fetchData: $error");
      return null;
    }
  }

  // Process and save step data by day
  Future<void> processAndSaveStepData(List<HealthDataPoint> dataPoints) async {
    Map<String, int> dailySteps = {};
    DateTime now = DateTime.now();

    for (var point in dataPoints) {
      if (point.type == HealthDataType.STEPS) {
        // Get the date part only (YYYY-MM-DD)
        String dateStr = StepDatabase._formatDate(point.dateFrom);

        // Add steps to the corresponding day
        dailySteps[dateStr] = (dailySteps[dateStr] ?? 0) + (point.value as NumericHealthValue).numericValue.toInt();
      }
    }

    // Save each day's data to the database
    for (var entry in dailySteps.entries) {
      String date = entry.key;
      int steps = entry.value;

      // Check if we already have data for this day
      final existingData = await database.getDailyStep(DateTime.parse(date));

      // If we have existing data, add to it (unless it's marked complete)
      if (existingData != null && !existingData.isComplete) {
        steps += existingData.stepCount;
      }

      // Determine if this day is complete (data is final)
      // We consider a day complete if it's before today
      bool isComplete = DateTime.parse(date).isBefore(DateTime(now.year, now.month, now.day));

      // Save to database
      await database.upsertDailyStep(date, steps, DateTime.now(), isComplete: isComplete);
    }
  }

  // Get only new data since last update
  Future<void> syncNewData() async {
    DateTime now = DateTime.now();
    DateTime startDate;

    // Get the last updated date from the database
    final lastUpdated = await database.getLastUpdatedDate();

    if (lastUpdated != null) {
      // If we have last updated date, start from 2 days before
      // (to handle possible midnight crossovers and timezone issues)
      startDate = lastUpdated.subtract(const Duration(days: 2));
    } else {
      // If no previous data, start from 30 days ago
      startDate = now.subtract(const Duration(days: 30));
    }

    // Fetch and process the data
    final healthData = await fetchData(startTime: startDate, endTime: now);

    if (healthData != null && healthData.isNotEmpty) {
      await processAndSaveStepData(healthData);
    }
  }

  // Refresh all data (last 30 days by default)
  Future<void> refreshAllData({int days = 30}) async {
    DateTime now = DateTime.now();
    DateTime startDate = now.subtract(Duration(days: days));

    // Clear existing data
    await database.deleteAllData();

    // Fetch and process fresh data
    final healthData = await fetchData(startTime: startDate, endTime: now);

    if (healthData != null && healthData.isNotEmpty) {
      await processAndSaveStepData(healthData);
    }
  }

  // Refresh data for a specific date range
  Future<void> refreshDataRange(DateTime start, DateTime end, {bool clearData = false}) async {
    // Delete data in the specified range
    await database.deleteDataInRange(start, end);

    if (clearData) {
      //TODO implement clear
      debugPrint("Start to clear database records");
      // Clear existing data logic
    }

    // Fetch and process fresh data for the range
    final healthData = await fetchData(
      startTime: start,
      endTime: end.add(const Duration(days: 1)), // Include the end date fully
    );

    if (healthData != null && healthData.isNotEmpty) {
      await processAndSaveStepData(healthData);
    }
  }
}

